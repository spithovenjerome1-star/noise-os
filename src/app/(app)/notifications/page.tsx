import Link from "next/link";
import { Bell, CheckCheck, AlertTriangle, AlertOctagon, Info, Zap } from "lucide-react";
import type { Severity } from "@prisma/client";
import { db } from "@/lib/db";
import { requireUser } from "@/server/auth";
import { PageHeader, EmptyState, SectionTitle } from "@/components/ui/misc";
import { Segmented } from "@/components/ui/tabs";
import { Card } from "@/components/ui/card";
import { Badge } from "@/components/ui/badge";
import { fmtMoment, timeAgo } from "@/lib/dates";
import { ActionButton } from "@/components/form";
import { markAllNotificationsRead, runAutomationsNow } from "@/server/automations/actions";
import { NotificationRow } from "./notification-row";

export const metadata = { title: "Inbox" };

const SEVERITY: { key: Severity; label: string; icon: React.ComponentType<{ className?: string }>; cls: string }[] = [
  { key: "CRITICAL", label: "Needs attention", icon: AlertOctagon, cls: "text-danger" },
  { key: "WARNING", label: "Coming up", icon: AlertTriangle, cls: "text-warning" },
  { key: "INFO", label: "For your information", icon: Info, cls: "text-info" },
];

export default async function NotificationsPage({ searchParams }: { searchParams: Promise<{ filter?: string }> }) {
  await requireUser();
  const { filter = "open" } = await searchParams;
  const where = filter === "resolved" ? { resolvedAt: { not: null } } : filter === "all" ? {} : { resolvedAt: null };
  const [items, runs, openCount] = await Promise.all([
    db.notification.findMany({ where, orderBy: [{ createdAt: "desc" }], take: 300, include: { client: { select: { name: true } } } }),
    db.automationRun.findMany({ orderBy: { startedAt: "desc" }, take: 6 }),
    db.notification.count({ where: { resolvedAt: null } }),
  ]);
  const unread = items.filter((n) => !n.readAt && !n.resolvedAt).length;

  return (
    <div className="grid gap-6 xl:grid-cols-[1fr_300px]">
      <div className="min-w-0">
        <PageHeader
          title="Inbox"
          description="Overdue videos, pending approvals, unpaid invoices and anything that needs a look. Generated by automations from your records."
          actions={
            <>
              {unread > 0 && (
                <ActionButton action={markAllNotificationsRead} size="sm" variant="ghost" successMessage={false}>
                  <CheckCheck /> Mark all read
                </ActionButton>
              )}
              <ActionButton action={runAutomationsNow} size="sm">
                <Zap /> Run automations now
              </ActionButton>
            </>
          }
        >
          <Segmented
            active={filter}
            items={[
              { key: "open", label: <>Open <span className="tabular text-subtle">{openCount}</span></>, href: "/notifications?filter=open" },
              { key: "resolved", label: "Resolved", href: "/notifications?filter=resolved" },
              { key: "all", label: "All", href: "/notifications?filter=all" },
            ]}
          />
        </PageHeader>

        {items.length === 0 ? (
          <EmptyState
            icon={Bell}
            title={filter === "open" ? "You're all caught up" : "Nothing here"}
            description={filter === "open" ? "No overdue videos, stale approvals or unpaid invoices right now." : "Resolved items will appear here."}
          />
        ) : (
          <div className="flex flex-col gap-6">
            {SEVERITY.map((s) => {
              const group = items.filter((n) => n.severity === s.key);
              if (!group.length) return null;
              const Icon = s.icon;
              return (
                <section key={s.key}>
                  <SectionTitle>
                    <span className="flex items-center gap-1.5">
                      <Icon className={`size-3.5 ${s.cls}`} /> {s.label} <span className="tabular">· {group.length}</span>
                    </span>
                  </SectionTitle>
                  <Card className="divide-y divide-border overflow-hidden">
                    {group.map((n) => (
                      <NotificationRow
                        key={n.id}
                        n={{ id: n.id, title: n.title, body: n.body, href: n.href, type: n.type, severity: n.severity, clientName: n.client?.name ?? null, read: Boolean(n.readAt), resolved: Boolean(n.resolvedAt), ago: timeAgo(n.createdAt) }}
                      />
                    ))}
                  </Card>
                </section>
              );
            })}
          </div>
        )}
      </div>

      <aside className="flex flex-col gap-3 xl:pt-14">
        <SectionTitle action={<Link href="/settings?tab=automations" className="text-xs text-muted hover:text-fg">Configure</Link>}>Automation runs</SectionTitle>
        <Card className="divide-y divide-border">
          {runs.length === 0 && <p className="px-4 py-4 text-[13px] text-muted">No runs yet.</p>}
          {runs.map((r) => (
            <div key={r.id} className="flex items-center justify-between gap-3 px-4 py-2.5">
              <div className="min-w-0">
                <div className="text-[13px]">{fmtMoment(r.startedAt, "d MMM, HH:mm")}</div>
                <div className="truncate text-xs text-subtle">{r.trigger.startsWith("manual") ? "Manual" : r.trigger === "cron" ? "Scheduled" : r.trigger === "cli" ? "Command line" : "Automatic"}</div>
              </div>
              {!r.finishedAt ? <Badge tone="info">Running</Badge> : r.error ? <Badge tone="warning">Errors</Badge> : <Badge tone="success">OK</Badge>}
            </div>
          ))}
        </Card>
        <p className="text-xs leading-relaxed text-subtle">
          Automations only create inbox items, periods and recurring expenses inside NOISE OS. They never email or message clients.
        </p>
      </aside>
    </div>
  );
}
